"""Step 0 go/no-go report, written to docs/step0.md (numbers only, no raw rows)."""
from __future__ import annotations

from collections import Counter

import pandas as pd

from sillage.config import ROOT, load_config
from sillage.data.catalogue import build_catalogue, parse_list
from sillage.data.ingest import read_products, read_reviews

GO_THRESHOLD = 1000


def _pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def run() -> dict:
    cfg = load_config()
    p = read_products()
    r = read_reviews()
    cat = build_catalogue(p)
    b_start = pd.Timestamp(cfg["periods"]["b_start"])
    c_start = pd.Timestamp(cfg["periods"]["c_start"])
    t = r["submission_time"]

    # Go / no-go: test users with history before C and a new liked product in C.
    pre = r[t < c_start]
    in_c = r[(t >= c_start) & (r["rating"] >= cfg["positive_min_rating"]) & ~r["incentivised"]]
    in_c = in_c[in_c["product_id"].isin(cat["product_id"])]
    seen = pd.MultiIndex.from_frame(pre[["author_id", "product_id"]])
    is_new = ~pd.MultiIndex.from_frame(in_c[["author_id", "product_id"]]).isin(seen)
    pos = in_c[is_new]
    hist_len = pre.groupby("author_id").size()
    test_users = pos.loc[pos["author_id"].isin(hist_len.index), "author_id"].unique()
    h = hist_len.reindex(test_users)
    first_seen = r.groupby("product_id")["submission_time"].min()
    launch_share = (pos["product_id"].map(first_seen) >= c_start).mean()

    val_users = r[(t >= b_start) & (t < c_start) & (r["rating"] >= 4) & ~r["incentivised"]]
    val_users = val_users["author_id"][val_users["author_id"].isin(r.loc[t < b_start, "author_id"])].nunique()

    per_author = r.groupby("author_id").size()
    n_by_product = r.groupby("product_id").size()
    cat["n_reviews"] = cat["product_id"].map(n_by_product).fillna(0)
    step_tbl = cat.groupby("step").agg(
        products=("product_id", "size"),
        with_20_reviews=("n_reviews", lambda s: int((s >= cfg["min_group_size"]).sum())),
        with_concern_tag=("concerns", lambda s: _pct((s.str.len() > 0).mean())),
        ingredients_missing=("ingredients_text", lambda s: _pct((s == "").mean())),
        median_price_usd=("price_usd", "median"),
    )
    tags = Counter(c for cs in cat["concerns"] for c in cs)
    sk = p[p["primary_category"] == "Skincare"]
    review_rate = n_by_product / p.set_index("product_id")["reviews"].reindex(n_by_product.index)

    go = len(test_users) >= GO_THRESHOLD
    out = {
        "products": len(p), "skincare": len(sk), "reviews": len(r),
        "authors": int(per_author.size), "test_users": int(len(test_users)),
        "val_users": int(val_users), "launch_share": float(launch_share), "go": go,
    }

    lines = [
        "# Step 0: data check (go / no-go)",
        "",
        f"Generated by `python -m sillage.build --stage step0`. Periods: A < {b_start.date()}, "
        f"B = {b_start.date()} to {c_start.date()}, C >= {c_start.date()}.",
        "",
        f"**Decision: {'GO' if go else 'NO-GO'}**: {len(test_users):,} test users have reviews "
        f"before C and at least one new liked routine product in C (threshold {GO_THRESHOLD:,}).",
        "",
        "## Size and coverage",
        f"- Products: {len(p):,} ({len(sk):,} skincare, {len(cat):,} in the three routine steps).",
        f"- Reviews after dedupe: {len(r):,} from {per_author.size:,} authors, "
        f"{t.min().date()} to {t.max().date()}.",
        f"- Scraped / listed reviews per product, median: {review_rate.median():.2f} (scrape is complete).",
        "",
        "## Missing values",
        f"- Reviews: is_recommended {_pct(r['is_recommended'].isna().mean())}, "
        f"skin_type {_pct(r['skin_type'].isna().mean())}.",
        f"- Skincare products: highlights {_pct(sk['highlights'].isna().mean())}, "
        f"ingredients {_pct(sk['ingredients'].isna().mean())}.",
        "- `highlights` and `ingredients` are Python-list strings; ingredients are free text and "
        "sometimes list several sub-products.",
        "",
        "## Routine steps",
        step_tbl.to_markdown(),
        "",
        "## Skin concerns",
        "Derived only from Sephora's `Good for: X` highlight tags on routine products:",
        "",
        ", ".join(f"{k} ({v})" for k, v in tags.most_common()),
        "",
        "## History",
        f"- Reviews per author: median {per_author.median():.0f}, "
        f"{_pct((per_author >= 2).mean())} have 2+, {_pct((per_author >= 5).mean())} have 5+.",
        f"- Validation users (liked in B, history in A): {val_users:,}.",
        "- History length of test users: "
        + ", ".join(f"{k}: {v:,}" for k, v in pd.cut(
            h, [0, 1, 4, 9, float("inf")], labels=["1", "2-4", "5-9", "10+"]
        ).value_counts().sort_index().items()) + ".",
        "",
        "## Findings that shape the design",
        f"- **Launches:** {_pct(launch_share)} of test positives are on products first reviewed "
        "inside C. Collaborative filtering cannot score them, so evaluation reports a catalogue "
        "slice and a launch slice.",
        f"- **Sampled reviews:** {_pct(r['incentivised'].mean())} of reviews mention a free or "
        "gifted product (a lower bound from a text rule). They are excluded from positives.",
        "- **Snapshot leakage:** product_info `rating`, `reviews` and `loves_count` are March 2023 "
        "values. They are never used as features.",
        "- **Survivorship:** products delisted before March 2023 are absent.",
        "",
    ]
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "step0.md").write_text("\n".join(lines), encoding="utf-8")
    return out
